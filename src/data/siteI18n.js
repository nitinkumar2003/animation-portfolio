/** Translate a key, interpolating {token} placeholders. Falls back to English. */
export const siteText = (language, key, vars) => {
  const value = siteStrings[language]?.[key] ?? en[key] ?? key;
  if (!vars) return value;
  return Object.entries(vars).reduce((text, [token, replacement]) => (
    text.replace(new RegExp(`\\{${token}\\}`, "g"), replacement)
  ), value);
};

